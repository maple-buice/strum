# mix gains (dB) applied at stem-mix time; class = onset label taxonomy
CLASS_GAIN = {
    "glockenspiel": ("glockenspiel", -8), "marimba": ("marimba", 0),
    "vibraphone": ("vibraphone", -1), "xylophone": ("xylophone", -3),
    "chimes": ("chimes", -3), "crotales": ("crotales", -8),
    "timpani_hit": ("timpani", 1), "timpani_roll": ("timpani", 0),
    "woodblock": ("woodblock", -5), "cowbell": ("cowbell", -6),
    "triangle": ("triangle", -9), "tambourine": ("tambourine", -5),
    "tambourine2": ("tambourine", -5), "shaker_large": ("shaker", -7),
    "shaker_small": ("shaker", -7), "cabasa": ("cabasa", -7),
    "snareline": ("snareline", -2), "tenorline": ("tenorline", -3),
    "bassline": ("bassline", -1), "cymballine": ("cymballine", -6),
}


def main():
    SFZ_DIR.mkdir(parents=True, exist_ok=True)
    convert_iowa_aiffs()
    reg = {}
    for name, (folder, pat) in PITCHED.items():
        reg[name] = build_pitched(name, folder, pat)
        print(f"built {name}: notes {reg[name]['sampled_notes']}")
    hit, roll = build_timpani()
    reg["timpani_hit"], reg["timpani_roll"] = hit, roll
    print(f"built timpani_hit: {hit['sampled_notes']}")
    print(f"built timpani_roll: {roll['sampled_notes']}")
    for name, folder in UNPITCHED.items():
        reg[name] = build_unpitched(name, folder)
        print(f"built {name}: artics {list(reg[name]['artics'])}")
    reg.update(mdl_instruments())
    for name, info in reg.items():
        cls, gain = CLASS_GAIN[name]
        info["class"] = cls
        info["gain_db"] = gain
    (SFZ_DIR / "mapping.json").write_text(json.dumps({"instruments": reg}, indent=1))
    print(f"wrote {SFZ_DIR / 'mapping.json'} with {len(reg)} instruments")


if __name__ == "__main__":
    main()
