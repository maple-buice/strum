# Unpitched VCSL instruments: articulation groups -> fixed keys from 60 up.
# --------------------------------------------------------------------------
UNPITCHED = {
    "woodblock": VCSL_SI / "Woodblock",
    "cowbell": VCSL_SI / "Cowbells",
    "triangle": VCSL_SI / "Triangles",
    "tambourine": VCSL_SI / "Tambourine 1",
    "tambourine2": VCSL_SI / "Tambourine 2",
    "shaker_large": VCSL_SI / "Shaker, Large",
    "shaker_small": VCSL_SI / "Shaker, Small",
    "cabasa": VCSL_SI / "Cabasa",
}


def build_unpitched(name, folder):
    lnk = _link(folder, name)
    # articulation group = filename minus rr / dyn / v / vl tokens
    table = defaultdict(lambda: defaultdict(list))  # group -> rank -> files
    for f in sorted(folder.rglob("*.wav")):
        if "Legacy" in f.parts[len(folder.parts):-1]:
            continue
        stem = f.stem
        stem = re.sub(r"_rr\d+", "", stem)
        stem = re.sub(r"_Mid$|_far$", "", stem)
        rank = 0
        m = re.search(r"_(pp|p|mp|mf|f|ff|fff)(?=_|$)", stem)
        if m:
            rank = DYN_RANK[m.group(1)]
            stem = stem[:m.start()] + stem[m.end():]
        m = re.search(r"_(?:v|vl)(\d+)(?=_|$)", stem)
        if m:
            rank = int(m.group(1))
            stem = stem[:m.start()] + stem[m.end():]
        rel = str(f.relative_to(folder)).replace("\\", "/")
        table[stem][rank].append(rel)
    artics = {}
    lines = [f"// generated by build_sfz.py  instrument={name}",
             "<control>", f"default_path=samples_lnk/{name}/",
             "<global> loop_mode=one_shot amp_veltrack=90"]
    for i, grp in enumerate(sorted(table)):
        key = 60 + 2 * i
        artics[grp] = key
        ranks = sorted(table[grp])
        for (lovel, hivel), rank in zip(_vel_bands(len(ranks)), ranks):
            files = sorted(table[grp][rank])
            for seq, fn in enumerate(files, 1):
                lines.append(_region(fn, {
                    "key": key, "lovel": lovel, "hivel": hivel,
                    "seq_length": len(files), "seq_position": seq}))
    (SFZ_DIR / f"{name}.sfz").write_text("\n".join(lines) + "\n")
    return {"sfz": f"{name}.sfz", "type": "unpitched", "artics": artics,
            "source_folder": str(folder.relative_to(ASSETS))}


