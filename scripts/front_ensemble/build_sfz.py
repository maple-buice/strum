"""Build SFZ instrument definitions from the downloaded sample libraries.

Outputs (all under ws5_assets/sfz/):
  <instrument>.sfz          generated SFZ for each VCSL/Iowa instrument
  mapping.json              machine-readable instrument registry used by the
                            arranger: per instrument -> sfz path, type
                            (pitched/unpitched), pitch range or articulation
                            key map, onset class label, mix gain (dB).
  samples_lnk/<Name>        space-free symlinks to the sample folders (SFZ
                            sample paths must not contain spaces).

MDL battery instruments use MDL's own (CC0) SFZ files unmodified; only their
key maps are recorded in mapping.json (keys read from the SFZ sources).

Timpani: VCSL timpani WAVs carry no pitch in the filename, so the fundamental
of each drum/tuning group is estimated with librosa.yin and the detected MIDI
key is written as pitch_keycenter (also dumped to timpani_pitches.json for
audit).
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (ASSETS, IOWA, MDL_SOUND, SFZ_DIR, VCSL_SI, VCSL_SM,
                    midi_to_note, note_to_midi)

DYN_RANK = {"pp": 0, "p": 1, "mp": 2, "mf": 3, "f": 4, "ff": 5, "fff": 6,
            "soft": 0, "med": 1, "medium": 1, "loud": 2, "hard": 2}

LNK = SFZ_DIR / "samples_lnk"


def _vel_bands(n):
    """Split 1..127 into n contiguous bands (low->high)."""
    edges = [1 + round(126 * i / n) for i in range(n)] + [127]
    return [(edges[i] + (1 if i else 0), edges[i + 1]) for i in range(n)]


def _link(folder: Path, name: str) -> Path:
    LNK.mkdir(parents=True, exist_ok=True)
    dst = LNK / name
    if not dst.is_symlink():
        dst.symlink_to(folder)
    return dst


def _region(sample, extra):
    kv = " ".join(f"{k}={v}" for k, v in extra.items())
    return f"<region> sample={sample} {kv}"


# --------------------------------------------------------------------------
# Pitched VCSL instruments: parse (note, dyn-layer, round-robin) from names.
# --------------------------------------------------------------------------
PITCHED = {
    "glockenspiel": (VCSL_SI / "Glockenspiel",
                     r"glock_(?P<dyn>soft|medium|loud)_(?P<note>[A-G]#?\d)_(?P<rr>\d+)\.wav"),
    "marimba": (VCSL_SI / "Marimba",
                r"Marimba_hit_Outrigger_(?P<note>[A-G]#?\d)_(?P<dyn>soft|med|loud)_(?P<rr>\d+)\.wav"),
    "vibraphone": (VCSL_SI / "Vibraphone",
                   r"Vibes_(?P<dyn>soft|hard)_(?P<note>[A-G]#?\d)(?:_v(?P<v>\d))?_rr(?P<rr>\d)_Main\.wav"),
    "xylophone": (VCSL_SI / "Xylophone",
                  r"Xylo_(?P<mallet>Soft|Medium|Hard)_(?P<note>[A-G]#?\d)_(?P<dyn>pp|ff)_(?P<rr>\d+)_far\.wav"),
    "chimes": (VCSL_SI / "Tubular Bells 1",
               r"chimes_(?P<note>[A-G]#?\d)_(?P<dyn>pp|p|mp|f|ff|fff)_rr(?P<rr>\d)\.wav"),
    "crotales": (IOWA / "Crotales_wav",
                 r"Crotale\.ff\.(?P<note>[A-G]b?\d)\.stereo\.wav"),
}
# xylophone: mallet+dyn combine into 6 velocity layers (soft/pp .. hard/ff)
XYLO_RANK = {("Soft", "pp"): 0, ("Soft", "ff"): 1, ("Medium", "pp"): 2,
             ("Medium", "ff"): 3, ("Hard", "pp"): 4, ("Hard", "ff"): 5}


def convert_iowa_aiffs():
    import soundfile as sf
    src = IOWA / "Crotales"
    dst = IOWA / "Crotales_wav"
    dst.mkdir(exist_ok=True)
    n = 0
    for f in sorted(src.glob("*.aif")):
        out = dst / (f.stem + ".wav")
        if not out.exists():
            data, sr = sf.read(f)
            sf.write(out, data, sr)
            n += 1
    print(f"iowa: converted {n} aiff->wav")


def build_pitched(name, folder, pat):
    lnk = _link(folder, name)
    # note -> dyn_rank -> [files]  (values are folder-relative paths)
    table = defaultdict(lambda: defaultdict(list))
    unmatched = []
    for f in sorted(folder.rglob("*.wav")):
        m = re.fullmatch(pat, f.name)
        if not m:
            unmatched.append(f.name)
            continue
        g = m.groupdict()
        if name == "xylophone":
            rank = XYLO_RANK[(g["mallet"], g["dyn"])]
        elif name == "vibraphone":
            # mallet soft/hard is the main layer; v-number sub-layers within
            rank = DYN_RANK[g["dyn"]] * 10 + int(g.get("v") or 0)
        elif "dyn" in g and g["dyn"]:
            rank = DYN_RANK[g["dyn"]]
        else:
            rank = 0
        rel = str(f.relative_to(folder)).replace("\\", "/")
        table[note_to_midi(g["note"])][rank].append(rel)
    if unmatched:
        print(f"  {name}: {len(unmatched)} unmatched files skipped: {unmatched[:4]}")

    notes = sorted(table)
    lines = [f"// generated by build_sfz.py  instrument={name}",
             "<control>", f"default_path=samples_lnk/{name}/",
             "<global> loop_mode=one_shot amp_veltrack=90"]
    for i, midi in enumerate(notes):
        lo = midi if i == 0 else (notes[i - 1] + midi) // 2 + 1
        hi = midi if i == len(notes) - 1 else (midi + notes[i + 1]) // 2
        ranks = sorted(table[midi])
        bands = _vel_bands(len(ranks))
        for (lovel, hivel), rank in zip(bands, ranks):
            files = sorted(table[midi][rank])
            for seq, fn in enumerate(files, 1):
                lines.append(_region(fn, {
                    "lokey": lo, "hikey": hi, "pitch_keycenter": midi,
                    "lovel": lovel, "hivel": hivel,
                    "seq_length": len(files), "seq_position": seq}))
    out = SFZ_DIR / f"{name}.sfz"
    out.write_text("\n".join(lines) + "\n")
    return {"sfz": out.name, "type": "pitched",
            "range": [min(notes), max(notes)],
            "sampled_notes": [midi_to_note(n) for n in notes],
            "source_folder": str(folder.relative_to(ASSETS))}


# --------------------------------------------------------------------------
# Timpani: pitch-detect each drum/tuning group, write hit + roll SFZs.
# --------------------------------------------------------------------------
def _detect_f0(path):
    import librosa
    import numpy as np
    y, sr = librosa.load(path, sr=22050, mono=True, offset=0.02, duration=1.5)
    f0 = librosa.yin(y, fmin=55, fmax=350, sr=sr, frame_length=2048)
    # keep frames with decent energy
    rms = librosa.feature.rms(y=y, frame_length=2048, hop_length=512)[0]
    n = min(len(f0), len(rms))
    f0, rms = f0[:n], rms[:n]
    good = f0[rms > 0.2 * rms.max()]
    hz = float(np.median(good if len(good) else f0))
    return hz, int(round(librosa.hz_to_midi(hz)))


def build_timpani():
    audit = {}

    def groups_of(folder, pat):
        g = defaultdict(list)
        for f in sorted(folder.glob("**/*.wav")):
            m = re.fullmatch(pat, f.name)
            if m:
                g[m.group("grp")].append((f, m.groupdict()))
        return g

    def make(name, folder, pat, gain_note):
        lnk = _link(folder, name)
        groups = groups_of(folder, pat)
        pitched = {}
        for grp, files in groups.items():
            hz, midi = _detect_f0(files[0][0])
            audit[f"{name}/{grp}"] = {"hz": round(hz, 1), "midi": midi,
                                      "note": midi_to_note(midi),
                                      "probe": files[0][0].name}
            pitched.setdefault(midi, []).extend(files)
        notes = sorted(pitched)
        lines = [f"// generated by build_sfz.py  instrument={name}",
                 f"// {gain_note}",
                 "<control>", f"default_path=samples_lnk/{name}/",
                 "<global> loop_mode=one_shot amp_veltrack=90"]
        for i, midi in enumerate(notes):
            lo = midi if i == 0 else (notes[i - 1] + midi) // 2 + 1
            hi = midi if i == len(notes) - 1 else (midi + notes[i + 1]) // 2
            byv = defaultdict(list)
            for f, g in pitched[midi]:
                byv[int(g.get("v") or 0)].append(f)
            ranks = sorted(byv)
            for (lovel, hivel), rank in zip(_vel_bands(len(ranks)), ranks):
                files = sorted(byv[rank], key=lambda p: p.name)
                for seq, f in enumerate(files, 1):
                    rel = f.relative_to(folder)
                    lines.append(_region(str(rel).replace("\\", "/"), {
                        "lokey": lo, "hikey": hi, "pitch_keycenter": midi,
                        "lovel": lovel, "hivel": hivel,
                        "seq_length": len(files), "seq_position": seq}))
        (SFZ_DIR / f"{name}.sfz").write_text("\n".join(lines) + "\n")
        return {"sfz": f"{name}.sfz", "type": "pitched",
                "range": [min(notes), max(notes)],
                "sampled_notes": [midi_to_note(n) for n in notes],
                "source_folder": str(folder.relative_to(ASSETS))}

    hit = make("timpani_hit", VCSL_SM / "Timpani 2",
               r"Timpani(?P<grp>\d[A-Z])_hit_v(?P<v>\d)_rr(?P<rr>\d)_main\.wav",
               "VCSL Timpani 2, pitch detected per drum/tuning group")
    roll = make("timpani_roll", VCSL_SM / "Timpani 1",
                r"Timpani(?P<grp>\d)_Roll_v(?P<v>\d)_rr(?P<rr>\d)_Sum\.wav",
                "VCSL Timpani 1 rolls, pitch detected per drum")
    (SFZ_DIR / "timpani_pitches.json").write_text(json.dumps(audit, indent=1))
    return hit, roll


